#!/usr/bin/env python3
"""Refresh `src/content/versions.rs` from the projects' release sources.

Two sources are supported:

* ``crate`` — the version crates.io reports as the latest stable release.
* ``tags``  — the highest semver-looking git tag on GitHub. Used for projects
  that are not published to a registry (ensia).
* ``manifest`` — the workspace version in the repository's `Cargo.toml`, with
  any pre-release suffix dropped. Used for aevia, which tags nothing and is
  still pre-1.0.

The script only ever moves a version *forward*. If a source is unreachable, or
reports something older than what the site already shows (a registry lagging
behind an announced release), the current value is kept and a warning printed.
Pass ``--force`` to accept whatever the source reports.

Run it by hand after a release, or let the scheduled deploy workflow do it:

    python3 scripts/update_versions.py            # write if something moved
    python3 scripts/update_versions.py --check    # exit 1 if stale, write nothing
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import sys
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "src", "content", "versions.rs")

# project key -> (constant, source kind, source name)
SOURCES = [
    ("dtact", "DTACT", "crate", "dtact"),
    ("ensia", "ENSIA", "tags", "ensia"),
    ("bincode", "BINCODE", "crate", "bincode-next"),
    ("rssn", "RSSN", "crate", "rssn"),
    ("cargo-slide", "CARGO_SLIDE", "crate", "cargo-slide"),
    ("virtue", "VIRTUE", "crate", "virtue-next"),
    ("aevia", "AEVIA", "manifest", "aevia"),
]

UA = "apich-site-version-bot/1.0 (+https://apich.org/)"
CONST_RE = re.compile(r'pub const (\w+): &str = "([^"]*)";')

HEADER = '''//! Published versions, one constant per project.
//!
//! This file is generated by `scripts/update_versions.py` and refreshed by the
//! scheduled deploy workflow. Do not edit it by hand: change the script if the
//! source of a version is wrong. Everything that displays a version — cards,
//! spec tables, install snippets, JSON-LD, `/data/projects.json`, `llms.txt` —
//! reads from here, so a release only needs one edit.

'''


def get_json(url: str) -> dict:
    headers = {"User-Agent": UA, "Accept": "application/json"}
    token = os.environ.get("GITHUB_TOKEN")
    if token and "api.github.com" in url:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=20) as resp:
        return json.load(resp)


def normalise(raw: str) -> str:
    """Strip a leading `v`, and a trailing `.0` only when the tag has four parts."""
    value = raw.strip()
    if value[:1] in ("v", "V"):
        value = value[1:]
    return value


def sort_key(version: str):
    parts = []
    for piece in re.split(r"[.+-]", version):
        match = re.match(r"\d+", piece)
        parts.append(int(match.group()) if match else 0)
    while len(parts) < 3:
        parts.append(0)
    return tuple(parts[:3])


def from_crate(name: str) -> str:
    data = get_json(f"https://crates.io/api/v1/crates/{name}")
    version = data.get("crate", {}).get("max_stable_version")
    if not version:
        raise ValueError("no max_stable_version in response")
    return normalise(version)


def from_tags(repo: str) -> str:
    data = get_json(f"https://api.github.com/repos/Apich-Organization/{repo}/tags?per_page=100")
    versions = [normalise(t["name"]) for t in data if re.fullmatch(r"v?\d+(\.\d+)*", t["name"].strip())]
    if not versions:
        raise ValueError("no semver tags found")
    return max(versions, key=sort_key)


def from_manifest(repo: str) -> str:
    url = f"https://raw.githubusercontent.com/Apich-Organization/{repo}/main/Cargo.toml"
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=20) as resp:
        body = resp.read().decode("utf-8", "replace")
    match = re.search(r'^version\s*=\s*"([^"]+)"', body, re.MULTILINE)
    if not match:
        raise ValueError("no version in Cargo.toml")
    value = match.group(1).split("-")[0]  # drop -beta.1 and friends
    if value.endswith(".0"):
        value = value[:-2]  # 0.1.0 reads better as 0.1
    return value


def read_current(text: str) -> dict:
    return dict(CONST_RE.findall(text))


def render(values: dict, checked: str) -> str:
    lines = [HEADER.rstrip("\n"), ""]
    lines.append(f'/// Date this file last changed, ISO 8601.')
    lines.append(f'pub const UPDATED: &str = "{checked}";')
    lines.append("")
    for _, const, _, _ in SOURCES:
        lines.append(f'pub const {const}: &str = "{values[const]}";')
    lines += [
        "",
        "/// `major.minor`, for dependency snippets such as `version = \"3.2\"`.",
        "///",
        "/// A bare `major` is kept as-is, so a language at `0.1` stays `0.1` rather than",
        "/// becoming `0.1.0`.",
        "pub fn minor(v: &str) -> String {",
        "    let parts: Vec<&str> = v.split('.').collect();",
        "    if parts.len() < 2 {",
        "        return v.to_string();",
        "    }",
        '    format!("{}.{}", parts[0], parts[1])',
        "}",
        "",
        "/// Replaces the `{version}` and `{v}` placeholders used in prose and snippets.",
        "pub fn fill(text: &str, version: &str) -> String {",
        '    text.replace("{version}", version)',
        '        .replace("{v}", &minor(version))',
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="report drift, change nothing")
    parser.add_argument("--force", action="store_true", help="accept older versions too")
    args = parser.parse_args()

    try:
        with open(TARGET, encoding="utf-8") as handle:
            text = handle.read()
    except FileNotFoundError:
        print(f"error: {TARGET} is missing", file=sys.stderr)
        return 2

    current = read_current(text)
    values = dict(current)
    changed = []

    for label, const, kind, name in SOURCES:
        old = current.get(const)
        if old is None:
            print(f"error: {const} is missing from versions.rs", file=sys.stderr)
            return 2
        try:
            if kind == "crate":
                new = from_crate(name)
            elif kind == "tags":
                new = from_tags(name)
            else:
                new = from_manifest(name)
        except (urllib.error.URLError, ValueError, KeyError, TimeoutError) as exc:
            print(f"  {label:12} {old:10} kept   ({kind} {name}: {exc})")
            continue
        if not args.force and sort_key(new) <= sort_key(old):
            note = "same" if sort_key(new) == sort_key(old) else "older, kept"
            print(f"  {label:12} {old:10} {note:12} (source says {new})")
            continue
        values[const] = new
        changed.append((label, old, new))
        print(f"  {label:12} {old:10} -> {new}")

    if not changed:
        print("versions are current")
        if args.check:
            return 0
        return 0

    if args.check:
        print(f"{len(changed)} project(s) are stale")
        return 1

    checked = dt.date.today().isoformat()
    # Keep whatever line ending the file already uses, so a refresh does not
    # rewrite every line on Windows checkouts.
    with open(TARGET, "rb") as handle:
        newline = "\r\n" if b"\r\n" in handle.read(4096) else "\n"
    with open(TARGET, "w", encoding="utf-8", newline=newline) as handle:
        handle.write(render(values, checked))
    print(f"wrote {os.path.relpath(TARGET, ROOT)} ({len(changed)} change(s), checked {checked})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
